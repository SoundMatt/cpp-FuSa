Level parse_level(const std::string& s) {
    if (s == "L1" || s == "1") return Level::L1;
    if (s == "L2" || s == "2") return Level::L2;
    if (s == "L3" || s == "3") return Level::L3;
    return Level::L4;
}
std::string level_str(Level l) {
    switch (l) {
        case Level::L1: return "SLSA-L1";
        case Level::L2: return "SLSA-L2";
        case Level::L3: return "SLSA-L3";
        default:        return "SLSA-L4";
    }
}
std::string status_str(Status s) {
    return (s == Status::Met) ? "satisfied" : "gap";
}

