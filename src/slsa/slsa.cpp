Status detect_status(const Requirement& req, const fs::path& dir) {
    if (req.id == "SLSA-1.1")
        return fs::exists(dir / "CMakeLists.txt") ? Status::Met : Status::Gap;
    if (req.id == "SLSA-1.2")
        return fs::exists(dir / "provenance.json") ? Status::Met : Status::Gap;
    if (req.id == "SLSA-1.3")
        return fs::exists(dir / "sbom.json") ? Status::Met : Status::Gap;
    if (req.id == "SLSA-2.4")
        return fs::exists(dir / ".git") ? Status::Met : Status::Gap;
    if (req.id == "SLSA-3.3")
        return fs::exists(dir / ".github" / "CODEOWNERS") ? Status::Met : Status::Gap;
    if (req.id == "SLSA-3.4")
        return fs::exists(dir / "provenance.json.sig") ? Status::Met : Status::Gap;
    return Status::Gap;
}

bool is_required(const Requirement& r, Level lvl) {
    switch (lvl) {
        case Level::L1: return r.required_l1;
        case Level::L2: return r.required_l2;
        case Level::L3: return r.required_l3;
        default:        return r.required_l4;
    }
}

