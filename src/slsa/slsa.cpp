//fusa:req REQ-SLSA003
Report assess(const fs::path& dir, const std::string& project, Level lvl) {
    Report r;
    r.project = project;
    r.level   = level_str(lvl);

    auto now = std::chrono::system_clock::now();
    auto t   = std::chrono::system_clock::to_time_t(now);
    std::ostringstream ts;
    ts << std::put_time(std::gmtime(&t), "%Y-%m-%dT%H:%M:%SZ");
    r.generated_at = ts.str();

    for (auto req : baseline_requirements()) {
        if (!is_required(req, lvl)) continue;
        req.status = detect_status(req, dir);
        r.requirements.push_back(req);
        r.total++;
        if (req.status == Status::Met) r.satisfied++;
        else                           r.gap++;
    }
    return r;
}

void write_json(const fs::path& out, const Report& r) {
    json j;
    j["generatedAt"] = r.generated_at;
    j["project"]     = r.project;
    j["level"]       = r.level;
    j["summary"]     = {{"total", r.total}, {"satisfied", r.satisfied}, {"gaps", r.gap}};
    j["requirements"] = json::array();
    for (auto& req : r.requirements) {
        j["requirements"].push_back({
            {"id", req.id}, {"description", req.description},
            {"status", status_str(req.status)}
        });
    }
    std::ofstream f(out);
    f << j.dump(2);
}

void render_text(const Report& r) {
    std::cout << "SLSA Provenance Report — " << r.project << " [" << r.level << "]\n";
    std::cout << std::string(70, '-') << "\n";
    for (auto& req : r.requirements) {
        const char* m = (req.status == Status::Met) ? "[OK]" : "[  ]";
        std::cout << m << " " << req.id << "  " << req.description << "\n";
    }
    std::cout << std::string(70, '-') << "\n";
    std::cout << "Total: " << r.total << "  Satisfied: " << r.satisfied << "  Gap: " << r.gap << "\n";
}

